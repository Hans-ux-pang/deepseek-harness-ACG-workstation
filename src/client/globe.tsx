function hashStr(s) {
  var h = 2166136261
  for (var i = 0; i < s.length; i++) {
    h = h ^ s.charCodeAt(i)
    h = (h * 16777619) >>> 0
  }
  return h >>> 0
}

function artSeed(seed) {
  var x = seed >>> 0
  return function () {
    x = (x * 1103515245 + 12345) % 2147483648
    return x / 2147483648
  }
}

function ridgePath(seed, baseY, amp, step) {
  var rnd = artSeed(seed)
  var d = 'M0 200 L0 ' + baseY
  for (var x = 0; x <= 320; x += step) {
    var y = baseY - amp * (0.2 + 0.8 * rnd())
    d += ' L' + x + ' ' + Math.round(y)
  }
  d += ' L320 200 Z'
  return d
}

