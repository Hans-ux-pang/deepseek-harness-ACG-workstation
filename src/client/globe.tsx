/**
 * 把服务端补充的城市目录并入内置点位。
 *
 * 规则：**内置点位优先** —— 补充点若落在任意已有点位 40km 内就丢弃，
 * 否则会出现「北京」与「Beijing」两个相隔 0km 的点；补充目录内部同样去重
 * （Natural Earth 里偶有相邻重名点）。`k` 是标记分级：0 = 内置点位（常显），
 * 1..3 = 补充点，随放大逐级显现，避免默认视图被 1200 个点糊满。
 */
function mergeCatalog(base, extra, minKm) {
  const out = base.map((d) => ({ n: d.n, e: d.e, c: d.c, f: d.f, lat: d.lat, lon: d.lon, t: d.t, k: 0 }))
  let dropped = 0   /* 与已有点位过近（内置点位优先） */
  let invalid = 0   /* 行结构或坐标非法 */
  for (const row of extra || []) {
    if (!Array.isArray(row) || row.length < 7) { invalid++; continue }
    const lat = Number(row[3])
    const lon = Number(row[4])
    /* 只判 isFinite 不够：999 也是有限数。越界坐标会投到荒唐位置，直接丢。 */
    if (!isFinite(lat) || !isFinite(lon) || lat < -90 || lat > 90 || lon < -180 || lon > 180) { invalid++; continue }
    const name = String(row[0] || '').trim()
    if (!name) { invalid++; continue }
    const p = { lat, lon }
    let dup = false
    for (const d of out) {
      if (hav(p, d) < minKm) { dup = true; break }
    }
    if (dup) { dropped++; continue }
    const pop = String(row[5] || '')
    const country = String(row[1] || '')
    out.push({
      n: name,
      e: name,
      c: country,
      f: String(row[2] || '📍'),
      lat, lon,
      t: (pop ? '人口约 ' + pop + '。' : '') + '坐标来自 Natural Earth 城市点。',
      k: 1 + Math.max(0, Math.min(2, Number(row[6]) || 0)),
    })
  }
  out.dropped = dropped
  out.invalid = invalid
  return out
}
