/* Natural Earth 110m 真实海岸线（TopoJSON）解码。
   TopoJSON 的 arcs 是「量化 + 增量」编码：每个点是相对前一个点的差值，
   再乘以 transform.scale 加上 transform.translate 才是经纬度。
   负的 arc 索引表示反向引用（~i === -i-1）。 */
function topoDecode(topo) {
  var outers = []
  var holes = []
  if (!topo || typeof topo !== 'object') return { outers: outers, holes: holes }
  var arcs = topo.arcs
  var tr = topo.transform
  if (!arcs || !arcs.length) return { outers: outers, holes: holes }

  /* 先把每条 arc 解成绝对经纬度点列 */
  var decoded = new Array(arcs.length)
  for (var i = 0; i < arcs.length; i++) {
    var arc = arcs[i]
    var pts = new Array(arc.length)
    var x = 0, y = 0
    for (var j = 0; j < arc.length; j++) {
      x += arc[j][0]
      y += arc[j][1]
      pts[j] = tr
        ? [x * tr.scale[0] + tr.translate[0], y * tr.scale[1] + tr.translate[1]]
        : [x, y]
    }
    decoded[i] = pts
  }

  /* 把一串 arc 索引拼成一个环；相邻 arc 的连接点会重复，跳过第一个 */
  function stitch(list) {
    var out = []
    for (var k = 0; k < list.length; k++) {
      var idx = list[k]
      var a = idx < 0 ? decoded[~idx].slice().reverse() : decoded[idx]
      if (!a) continue
      for (var m = out.length ? 1 : 0; m < a.length; m++) out.push(a[m])
    }
    return out
  }

  function addRings(rings) {
    for (var r = 0; r < rings.length; r++) {
      var ring = stitch(rings[r])
      if (ring.length < 3) continue
      if (r === 0) outers.push(ring)
      else holes.push(ring)
    }
  }

  var root = topo.objects && topo.objects.land
  var geoms = root && root.geometries ? root.geometries : (root ? [root] : [])
  for (var g = 0; g < geoms.length; g++) {
    var geo = geoms[g]
    if (!geo || !geo.arcs) continue
    if (geo.type === 'Polygon') addRings(geo.arcs)
    else if (geo.type === 'MultiPolygon') {
      for (var p = 0; p < geo.arcs.length; p++) addRings(geo.arcs[p])
    }
  }
  return { outers: outers, holes: holes }
}

/* 为每个多边形预计算「中心 + 角半径」，用于每帧快速剔除背面形状：
   这样做之后，只有可能出现在可见半球上的多边形才会逐点投影。 */
function polyMeta(polys) {
  var meta = new Array(polys.length)
  for (var i = 0; i < polys.length; i++) {
    var p = polys[i]
    var sx = 0, sy = 0, sz = 0
    var latMin = 90, latMax = -90, lonMin = 180, lonMax = -180
    for (var j = 0; j < p.length; j++) {
      var la = p[j][1] * RAD, lo = p[j][0] * RAD
      var cl = Math.cos(la)
      sx += cl * Math.cos(lo)
      sy += cl * Math.sin(lo)
      sz += Math.sin(la)
      if (p[j][1] < latMin) latMin = p[j][1]
      if (p[j][1] > latMax) latMax = p[j][1]
      if (p[j][0] < lonMin) lonMin = p[j][0]
      if (p[j][0] > lonMax) lonMax = p[j][0]
    }
    var n = Math.max(1, p.length)
    var cx = sx / n, cy = sy / n, cz = sz / n
    var len = Math.sqrt(cx * cx + cy * cy + cz * cz)
    if (len < 1e-9) { cx = 1; cy = 0; cz = 0; len = 1 }
    cx /= len; cy /= len; cz /= len
    var maxAng = 0
    for (var k = 0; k < p.length; k++) {
      var la2 = p[k][1] * RAD, lo2 = p[k][0] * RAD
      var d = cx * Math.cos(la2) * Math.cos(lo2) + cy * Math.cos(la2) * Math.sin(lo2) + cz * Math.sin(la2)
      var ang = Math.acos(clamp(d, -1, 1))
      if (ang > maxAng) maxAng = ang
    }
    meta[i] = {
      x: cx, y: cy, z: cz, r: maxAng,
      latMin: latMin, latMax: latMax, lonMin: lonMin, lonMax: lonMax,
    }
  }
  return meta
}

/* 冰盖判定：只保留「整块都在高南纬」这一条 —— 也就是南极洲。
   注意 Natural Earth 110m 把格陵兰并进了美洲那个大连通块
   （实测：包含 72°N/40°W 的环 latMin 是 −34.8°、经度横跨 −180..180），
   所以没法单独给它上色，硬判只会把整块美洲一起刷白。 */
function isIcePoly(m) {
  return !!m && m.latMax < -55
}

/* 多边形是否可能出现在可见半球上 */
function polyVisible(m, B) {
  var d = m.x * B.vx + m.y * B.vy + m.z * B.vz
  return Math.acos(clamp(d, -1, 1)) <= Math.PI / 2 + m.r + 0.02
}

/* 太阳直射点（粗略）：由 UTC 时间与日期得到，用于昼夜明暗 */
function subsolarPoint(ms) {
  if (!ms) return { lat: 15, lon: 0 }
  var dayMs = 86400000
  var days = ms / dayMs
  var frac = days - Math.floor(days)
  /* 世界时 12:00 时 0° 经线正对太阳 */
  var lon = wrapLon(180 - frac * 360)
  /* 黄赤交角引起的直射点纬度变化（近似，够用） */
  var yearFrac = (days % 365.2422) / 365.2422
  var lat = 23.44 * Math.sin(2 * Math.PI * (yearFrac - 0.22))
  return { lat: lat, lon: lon }
}

/* 地固坐标下的单位向量 */
function geoVec(lat, lon) {
  var la = lat * RAD, lo = lon * RAD
  var cl = Math.cos(la)
  return { x: cl * Math.cos(lo), y: cl * Math.sin(lo), z: Math.sin(la) }
}

/* 世界向量 → 观察坐标系分量（与 project 同一套基向量） */
function toView(v, B) {
  return {
    x: v.x * B.ex + v.y * B.ey + v.z * B.ez,
    y: v.x * B.nx + v.y * B.ny + v.z * B.nz,
    z: v.x * B.vx + v.y * B.vy + v.z * B.vz,
  }
}

/* 选一条边缘弧，使围出的区域落在夜侧：取候选弧中点，反投影后与太阳方向点乘判断。
   这条规则可以直接用单元测试验证，不靠猜。 */
function limbDirNight(a0, a1, sun, B, cx, cy, R) {
  if (a0 === null || a1 === null || a0 === undefined || a1 === undefined) return null
  var d = a1 - a0
  while (d > Math.PI) d -= Math.PI * 2
  while (d < -Math.PI) d += Math.PI * 2
  var mid = limbPoint(a0 + d * 0.5, B, cx, cy, R)
  var v = geoVec(mid.lat, mid.lon)
  var dot = v.x * sun.x + v.y * sun.y + v.z * sun.z
  if (dot < 0) return d
  return d > 0 ? d - Math.PI * 2 : d + Math.PI * 2
}

/* 沿边缘圆补一段弧，方向由方向角 d 决定 */
function appendLimb(ring, a0, d, B, cx, cy, R) {
  if (a0 === null || a0 === undefined || d === null || d === undefined) return
  var steps = Math.max(2, Math.ceil(Math.abs(d) / 0.06))
  for (var s = 1; s <= steps; s++) {
    var lp = limbPoint(a0 + d * (s / steps), B, cx, cy, R)
    ring.push([lp.x, lp.y])
  }
}

/* 晨昏线：与太阳方向垂直的大圆，它把球面分成昼半球与夜半球。
   这里直接返回「可见盘面 ∩ 夜半球」的**屏幕闭合折线**，
   draw() 只负责 fill，测试也能直接对这条折线做点包含检查。 */
function terminatorNight(sun, B, cx, cy, R) {
  /* 太阳几乎正对视角中心时整盘都是白天；此时晨昏线退化到贴住边缘，
     直接不画，避免退化成一个覆盖全盘的环 */
  var sunView = toView(sun, B)
  if (sunView.z > 0.9995) return { mode: 'none' }

  /* 与 sun 正交的一组基 */
  var ax = 0, ay = 0, az = 1
  if (Math.abs(sun.z) > 0.9) { ax = 1; ay = 0; az = 0 }
  var ux = sun.y * az - sun.z * ay
  var uy = sun.z * ax - sun.x * az
  var uz = sun.x * ay - sun.y * ax
  var ul = Math.sqrt(ux * ux + uy * uy + uz * uz)
  if (ul < 1e-9) return { mode: 'none' }
  ux /= ul; uy /= ul; uz /= ul
  var vx = sun.y * uz - sun.z * uy
  var vy = sun.z * ux - sun.x * uz
  var vz = sun.x * uy - sun.y * ux

  var N = 96
  var samples = new Array(N)
  var anyVis = false
  for (var i = 0; i < N; i++) {
    var t = (i / N) * Math.PI * 2
    var ct = Math.cos(t), st = Math.sin(t)
    var w = { x: ct * ux + st * vx, y: ct * uy + st * vy, z: ct * uz + st * vz }
    var vp = toView(w, B)
    var vis = vp.z >= 0
    if (vis) anyVis = true
    samples[i] = {
      x: cx + R * vp.x, y: cy - R * vp.y,
      /* 与 limbPoint 同一套角度约定：x = cx + R cosθ, y = cy − R sinθ */
      a: Math.atan2(vp.y, vp.x),
      vis: vis,
      z: vp.z,
    }
  }
  /* 晨昏线完全不与可见盘面相交 → 整个可见盘面同属一侧 */
  if (!anyVis) return { mode: 'full' }

  /* 按可见性切成若干段（与 buildRuns 同一套做法） */
  var start = 0
  for (var s = 0; s < N; s++) if (!samples[s].vis) { start = s; break }
  function crossing(a, b) {
    var k = a.z / (a.z - b.z)
    var px = a.x + (b.x - a.x) * k
    var py = a.y + (b.y - a.y) * k
    /* 屏幕 y 轴朝下，所以角度用的是 cy − py */
    return { x: px, y: py, a: Math.atan2(cy - py, px - cx) }
  }
  var runs = []
  var cur = null
  for (var q = 0; q < N; q++) {
    var i0 = (start + q) % N, i1 = (start + q + 1) % N
    var A = samples[i0], C = samples[i1]
    if (A.vis) {
      if (!cur) cur = { pts: [], inA: null, outA: null }
      cur.pts.push([A.x, A.y])
      if (!C.vis) {
        var h1 = crossing(A, C)
        cur.pts.push([h1.x, h1.y])
        cur.outA = h1.a
        runs.push(cur)
        cur = null
      }
    } else if (C.vis) {
      var h2 = crossing(A, C)
      cur = { pts: [[h2.x, h2.y]], inA: h2.a, outA: null }
    }
  }
  if (cur) runs.push(cur)
  if (!runs.length) return { mode: 'full' }

  var ring = []
  for (var r = 0; r < runs.length; r++) {
    if (r > 0) {
      var from = runs[r - 1].outA
      var d = limbDirNight(from, runs[r].inA, sun, B, cx, cy, R)
      appendLimb(ring, from, d, B, cx, cy, R)
    }
    for (var m = 0; m < runs[r].pts.length; m++) ring.push(runs[r].pts[m])
  }
  /* 收口：从最后一段的出口沿边缘回到第一段的入口 */
  var lastA = runs[runs.length - 1].outA
  var dClose = limbDirNight(lastA, runs[0].inA, sun, B, cx, cy, R)
  appendLimb(ring, lastA, dClose, B, cx, cy, R)
  return { mode: 'path', ring: ring }
}
