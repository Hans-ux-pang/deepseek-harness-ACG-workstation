/** 各缩放档位显示到哪一级标记。默认视图与改动前一致（只显示内置 347 个）。 */
function tierForZoom(zoom: number): number {
  if (zoom < 1.1) return 0
  if (zoom < 1.3) return 1
  if (zoom < 1.6) return 2
  return 3
}

/** 目的地实景图候选（客户端缓存，同一次会话内同名目的地只请求一次）。 */
