var RAD = Math.PI / 180
var EARTH_R = 6371

function clamp(v, a, b) { return v < a ? a : (v > b ? b : v) }

function wrapLon(lon) {
  var x = ((lon + 180) % 360 + 360) % 360 - 180
  return x
}

/* 两点大圆距离（km） */
function hav(a, b) {
  var p1 = a.lat * RAD, p2 = b.lat * RAD
  var dp = (b.lat - a.lat) * RAD, dl = (b.lon - a.lon) * RAD
  var s = Math.sin(dp / 2) * Math.sin(dp / 2) +
    Math.cos(p1) * Math.cos(p2) * Math.sin(dl / 2) * Math.sin(dl / 2)
  return 2 * EARTH_R * Math.asin(clamp(Math.sqrt(s), 0, 1))
}

/* 大圆插值：球面两点之间按比例取点 */
function slerp(a, b, t) {
  var p1 = a.lat * RAD, l1 = a.lon * RAD, p2 = b.lat * RAD, l2 = b.lon * RAD
  var v1x = Math.cos(p1) * Math.cos(l1), v1y = Math.cos(p1) * Math.sin(l1), v1z = Math.sin(p1)
  var v2x = Math.cos(p2) * Math.cos(l2), v2y = Math.cos(p2) * Math.sin(l2), v2z = Math.sin(p2)
  var d = clamp(v1x * v2x + v1y * v2y + v1z * v2z, -1, 1)
  var w = Math.acos(d)
  if (w < 1e-7) return { lat: a.lat, lon: a.lon }
  var s = Math.sin(w)
  var c1 = Math.sin((1 - t) * w) / s, c2 = Math.sin(t * w) / s
  var x = c1 * v1x + c2 * v2x, y = c1 * v1y + c2 * v2y, z = c1 * v1z + c2 * v2z
  return { lat: Math.asin(clamp(z, -1, 1)) / RAD, lon: Math.atan2(y, x) / RAD }
}

/* 观察坐标系基向量：east / north' / view */
function makeBasis(lon0, lat0) {
  var l0 = lon0 * RAD, p0 = lat0 * RAD
  return {
    lon0: lon0, lat0: lat0,
    cp0: Math.cos(p0), sp0: Math.sin(p0),
    ex: -Math.sin(l0), ey: Math.cos(l0), ez: 0,
    nx: -Math.sin(p0) * Math.cos(l0), ny: -Math.sin(p0) * Math.sin(l0), nz: Math.cos(p0),
    vx: Math.cos(p0) * Math.cos(l0), vy: Math.cos(p0) * Math.sin(l0), vz: Math.sin(p0),
  }
}

/* 正交投影：经纬度 → 屏幕坐标 / 可见性 */
function project(lon, lat, cx, cy, R, B) {
  var p = lat * RAD, dl = (lon - B.lon0) * RAD
  var cp = Math.cos(p), sp = Math.sin(p), cdl = Math.cos(dl), sdl = Math.sin(dl)
  var x = cp * sdl
  var y = B.cp0 * sp - B.sp0 * cp * cdl
  var z = B.sp0 * sp + B.cp0 * cp * cdl
  return { x: cx + R * x, y: cy - R * y, vx: x, vy: y, z: z, vis: z >= 0 }
}

/* 正交逆投影：屏幕坐标 → 经纬度（球外返回 null） */
function unproject(mx, my, cx, cy, R, B) {
  var x = (mx - cx) / R, y = -(my - cy) / R
  var d2 = x * x + y * y
  if (d2 > 1) return null
  var z = Math.sqrt(Math.max(0, 1 - d2))
  var wx = x * B.ex + y * B.nx + z * B.vx
  var wy = x * B.ey + y * B.ny + z * B.vy
  var wz = x * B.ez + y * B.nz + z * B.vz
  return { lat: Math.asin(clamp(wz, -1, 1)) / RAD, lon: Math.atan2(wy, wx) / RAD }
}

/* 屏幕边缘圆上某个角度所对应的经纬度 */
function limbPoint(theta, B, cx, cy, R) {
  var x = Math.cos(theta), y = Math.sin(theta)
  var wx = x * B.ex + y * B.nx
  var wy = x * B.ey + y * B.ny
  var wz = x * B.ez + y * B.nz
  return {
    x: cx + R * x, y: cy - R * y,
    lat: Math.asin(clamp(wz, -1, 1)) / RAD,
    lon: Math.atan2(wy, wx) / RAD,
  }
}

/* 射线法：点在经纬度多边形内 */
function inPoly(lon, lat, poly) {
  var inside = false
  for (var i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    var xi = poly[i][0], yi = poly[i][1], xj = poly[j][0], yj = poly[j][1]
    if (((yi > lat) !== (yj > lat)) && (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi)) {
      inside = !inside
    }
  }
  return inside
}

function ease(t) {
  return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2
}
