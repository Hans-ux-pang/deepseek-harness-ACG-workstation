function findNearest(lat, lon) {
  var best = null, bd = Infinity
  for (var i = 0; i < DESTS.length; i++) {
    var d = hav({ lat: lat, lon: lon }, DESTS[i])
    if (d < bd) { bd = d; best = DESTS[i] }
  }
  return { dest: best, km: bd }
}

/* 把一次点击解释成一段旅程 */
function describe(lat, lon, fromPoint) {
  var near = findNearest(lat, lon)
  var land = landAt(lat, lon)
  var region = land || oceanName(lat, lon)
  var snap = near.km <= 650
  var legKm = fromPoint ? Math.round(hav(fromPoint, snap ? near.dest : { lat: lat, lon: lon })) : 0
  return {
    snap: snap,
    dest: snap ? near.dest : null,
    near: near.dest,
    nearKm: Math.round(near.km),
    lat: lat,
    lon: lon,
    land: !!land,
    region: region,
    legKm: legKm,
    anchor: snap ? { lat: near.dest.lat, lon: near.dest.lon } : { lat: lat, lon: lon },
  }
}
