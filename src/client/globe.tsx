/**
 * 把一个环的经度展开成连续序列。
 * 跨 ±180° 的环（欧亚大陆就是）直接在经纬度平面上做射线法会数错交点
 * —— 实测罗瓦涅米因此被误判成「不在陆地上」。
 */
function unwrapRing(ring) {
  var out = [[ring[0][0], ring[0][1]]]
  for (var i = 1; i < ring.length; i++) {
    var lon = ring[i][0]
    var prev = out[i - 1][0]
    while (lon - prev > 180) lon -= 360
    while (lon - prev < -180) lon += 360
    out.push([lon, ring[i][1]])
  }
  return out
}

/** 海岸线数据到位后预处理一次：外环与空洞都展开经度。 */
function buildUnwrapped(world) {
  if (!world || !world.all) return null
  return {
    outers: world.all.slice(0, world.outerCount).map(unwrapRing),
    holes: world.all.slice(world.outerCount).map(unwrapRing),
  }
}

/**
 * 真实海陆判定（用 Natural Earth 海岸线，经度展开 + ±360 偏移试三次）。
 * 返回 true/false；没有数据时返回 null 表示「未知」，由调用方回退内置手绘轮廓。
 */
function realLandAt(lat, lon, u) {
  if (!u) return null
  var hit = function (rings) {
    for (var k = -1; k <= 1; k++) {
      var L = lon + k * 360
      for (var i = 0; i < rings.length; i++) {
        if (inPoly(L, lat, rings[i])) return true
      }
    }
    return false
  }
  if (!hit(u.outers)) return false
  if (u.holes.length && hit(u.holes)) return false
  return true
}

/**
 * 本地太阳时（按经度估算，UTC + lon/15）。
 * nowMs 可注入，方便测试确定性地推进时间；省略则取当前时间。
 */
function solarHour(lon, nowMs) {
  var off = Math.round(lon / 15)
  var t = (nowMs || Date.now()) + off * 3600000
  return Math.floor(t / 3600000) % 24
}

function hourWord(h) {
  if (h < 5) return '深夜'
  if (h < 8) return '清晨'
  if (h < 11) return '上午'
  if (h < 14) return '正午前后'
  if (h < 17) return '下午'
  if (h < 20) return '傍晚'
  if (h < 23) return '夜里'
  return '深夜'
}

function poemPick(list, seed) {
  /* hashStr 返回的是 >>> 0 的无符号值，一旦有人用有符号 >> 处理，下标就会变成负数、
     取到 undefined —— 界面上表现为凭空多出一个句号。这里统一兜住。 */
  var i = Math.abs(Math.floor(seed)) % list.length
  return list[i]
}

/**
 * 为任意地点生成一句诗意解读。
 * @param d 目的地（至少要有 n / lat / lon / k / c）
 * @param _nowMs 可注入的时间戳（便于测试确定性；省略则取当前时间）
 * @param u 展开后的海岸线数据（buildUnwrapped 的产物）；缺省则回退内置手绘轮廓
 */
function poeticLine(d, _nowMs, u) {
  if (!d) return ''
  var seed = hashStr(String(d.n) + '|' + String(d.lat))
  var alat = Math.abs(d.lat)
  var band = alat > 66 ? 'polar'
    : alat > 50 ? 'high'
      : alat > 35 ? 'temperate'
        : alat > 23.5 ? 'subtrop'
          : alat > 10 ? 'tropic' : 'equator'
  var light = poemPick(POEM_LIGHT[band], seed)

  /* 海陆：冰盖 → 陆地 → 水上，三级都据实说 */
  var onLand = realLandAt(d.lat, d.lon, u)
  if (onLand === null) onLand = !!landAt(d.lat, d.lon)
  var continent = landAt(d.lat, d.lon)
  var place
  if (alat >= 84) {
    place = poemPick(POEM_LAND.ice, seed >>> 4)
  } else if (onLand) {
    var where = continent || (d.c && d.c !== '公海' && d.c !== '无名之地' ? d.c : '')
    place = where ? '它落在' + where + '的土地上' : '这里有自己的天亮天黑'
  } else {
    place = poemPick(POEM_LAND.ocean, seed >>> 3)
  }

  var bits = [light, place]
  /* 南半球的季节与北半球相反 —— 这条是真的，值得点出来 */
  if (d.lat < 0) bits.push('南半球的一切都比北边晚半年，这里入夏时北边正在落雪')
  /* 人声密度只在有人口数据支撑时提（k>=1 来自城市目录），避免给南极点配一句「街道」 */
  if ((d.k || 0) === 1) bits.push('人声与灯火在这里聚成一片')
  else if ((d.k || 0) >= 2) bits.push('安静是这里最主要的声响')

  bits.push('你抵达时，这里大约正是' + hourWord(solarHour(d.lon, _nowMs)))
  return bits.join('。') + '。'
}
